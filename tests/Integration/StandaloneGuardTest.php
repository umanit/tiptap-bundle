<?php

declare(strict_types=1);

namespace Umanit\TiptapBundle\Tests\Integration;

use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * The bundle must stay standalone: no reference to the host application, to a CSS framework or to unexpected
 * Twig namespaces and JS packages.
 */
#[CoversNothing]
final class StandaloneGuardTest extends TestCase
{
    private const array SCANNED_DIRECTORIES = [
        'src',
        'templates',
        'translations',
        'config',
        'assets/src',
        'assets/dist',
    ];
    private const array SCANNED_EXTENSIONS = ['php', 'twig', 'yaml', 'js', 'css'];

    /**
     * @return iterable<string, array{string, string}>
     */
    public static function provideForbiddenPatterns(): iterable
    {
        // Allow-lists: anything which is not explicitly expected is reported.
        yield 'Twig namespaces other than the bundle one' => [
            '/[\'"]@(?!UmanitTiptap\b|umanit\/)[A-Za-z]\w*\//',
            'php,twig',
        ];
        yield 'JS imports other than relative or expected packages' => [
            '/^\s*(?:import|export)\b[^\n]*\bfrom\s+\'(?!\.{1,2}\/|@tiptap\/|@hotwired\/stimulus\'|'
            . '@intevation\/tiptap-extension-office-paste\')[^\']+\'/m',
            'js',
        ];
        yield 'Application namespace' => ['/\bApp\\\\/', 'php,twig,yaml,js'];
        yield 'Bootstrap classes' => [
            '/(?:["\'\s])(?:form-(?:control|select|label|check\S*)|btn(?:-\S+)?|d-none|bs-\S+)(?=["\'\s])/',
            'twig,js,css',
        ];
        yield 'Bootstrap data attributes' => ['/data-bs-/', 'twig,js'];
        yield 'Font Awesome icons' => ['/\bfa6-solid:|\bfa-solid\b/', 'twig,php,js'];
        yield 'Icon set of the host' => ['/[\'"]lucide:/', 'twig,php,js'];
    }

    #[DataProvider('provideForbiddenPatterns')]
    public function testNoForbiddenReference(string $pattern, string $extensions): void
    {
        $extensions = explode(',', $extensions);
        $offenders = [];

        foreach ($this->listFiles() as $file) {
            if (!\in_array(pathinfo($file, \PATHINFO_EXTENSION), $extensions, true)) {
                continue;
            }

            $content = (string) file_get_contents($file);

            if (1 === preg_match($pattern, $content, $matches)) {
                $offenders[] = \sprintf('%s (%s)', substr($file, \strlen($this->root()) + 1), trim($matches[0]));
            }
        }

        $this->assertSame([], $offenders);
    }

    /**
     * @return list<string>
     */
    private function listFiles(): array
    {
        $files = [];

        foreach (self::SCANNED_DIRECTORIES as $directory) {
            $path = $this->root() . '/' . $directory;

            if (!is_dir($path)) {
                continue;
            }

            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS),
            );

            /** @var \SplFileInfo $file */
            foreach ($iterator as $file) {
                if (
                    $file->isFile()
                    && \in_array($file->getExtension(), self::SCANNED_EXTENSIONS, true)
                    && !str_contains($file->getPathname(), 'node_modules')
                    // Generated by Symfony: documents the `App\` namespace of the host application.
                    && 'reference.php' !== $file->getFilename()
                ) {
                    $files[] = $file->getPathname();
                }
            }
        }

        return $files;
    }

    private function root(): string
    {
        return \dirname(__DIR__, 2);
    }
}
