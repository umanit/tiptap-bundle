<?php

declare(strict_types=1);

namespace Umanit\TiptapBundle\Palette;

/**
 * Renders a palette as the files an application needs: its colors set builder, the CSS of the classes and the map of
 * the legacy import mode.
 */
final readonly class PaletteRenderer
{
    public function renderBuilder(Palette $palette, string $class, string $indexName = 'default'): string
    {
        if (1 !== preg_match('/^\\\\?(?:[A-Za-z_]\w*\\\\)*[A-Za-z_]\w*$/', $class)) {
            throw new \InvalidArgumentException(\sprintf('"%s" is not a valid class name.', $class));
        }

        $parts = explode('\\', ltrim($class, '\\'));
        $shortName = array_pop($parts);
        $namespace = [] === $parts ? '' : \sprintf("namespace %s;\n\n", implode('\\', $parts));

        $colors = implode(
            "\n            ",
            array_map(
                static fn(PaletteColor $color): string => \sprintf(
                    "new Color('%s', '%s'), // %s",
                    ucfirst(str_replace('-', ' ', $color->name)),
                    $color->name,
                    $color->hex,
                ),
                $palette->colors,
            ),
        );

        return <<<PHP
            <?php

            declare(strict_types=1);

            {$namespace}use Umanit\\TiptapBundle\\Builder\\ColorsSetBuilderInterface;
            use Umanit\\TiptapBundle\\DTO\\Color;
            use Umanit\\TiptapBundle\\DTO\\ColorsSet;

            /**
             * Generated by `umanit:tiptap:palette` from existing contents: the names are generic, rename them.
             */
            final readonly class {$shortName} implements ColorsSetBuilderInterface
            {
                public static function getDefaultIndexName(): string
                {
                    return '{$indexName}';
                }

                public function build(): ColorsSet
                {
                    return new ColorsSet([
                        {$colors}
                    ]);
                }
            }

            PHP;
    }

    public function renderCss(Palette $palette): string
    {
        $css = "/* Generated by `umanit:tiptap:palette` from existing contents. */\n\n:root {\n";

        foreach ($palette->colors as $color) {
            $css .= \sprintf("  --ut-color-%s: %s;\n", $color->name, $color->hex);
        }

        $css .= "}\n\n/* Text colors */\n";

        foreach ($palette->colors as $color) {
            $css .= \sprintf(".ut-color-%s { color: var(--ut-color-%s); }\n", $color->name, $color->name);
        }

        $css .= "\n/* Background colors */\n";

        foreach ($palette->colors as $color) {
            $css .= \sprintf(
                ".ut-bg-%s { background-color: var(--ut-color-%s) !important; }\n",
                $color->name,
                $color->name,
            );
        }

        $css .= "\n/* Font sizes */\n";

        foreach ($palette->sizes as $size) {
            $css .= \sprintf(".%s { font-size: %dpx; }\n", $size->getClass(), $size->pixels);
        }

        return $css;
    }

    public function renderLegacyStyles(Palette $palette): string
    {
        return json_encode(
            $palette->toLegacyStyles(),
            \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES | \JSON_THROW_ON_ERROR,
        ) . "\n";
    }
}
